/*
 * MT6833 has multiple bases to program pin configuration, listed below:
 * GPIO_BASE:     0x10005000
 * IOCFG_RB_BASE: 0x11c30000
 * IOCFG_BM_BASE: 0x11d10000
 * IOCFG_BR_BASE: 0x11d40000
 * IOCFG_LM_BASE: 0x11e20000
 * IOCFG_BL_BASE: 0x11e60000
 * IOCFG_RT_BASE: 0x11ea0000
 * _i_based could be used to indicate what base the pin should be mapped into.
 */

#define PIN_FIELD_BASE(s_pin, e_pin, i_base, s_addr, x_addrs, s_bit, x_bits)  \
	PIN_FIELD_CALC(s_pin, e_pin, i_base, s_addr, x_addrs, s_bit, x_bits, \
		32, 0)

#define PINS_FIELD_BASE(s_pin, e_pin, i_base, s_addr, x_addrs, s_bit, x_bits) \
	PIN_FIELD_CALC(s_pin, e_pin, i_base, s_addr, x_addrs, s_bit, x_bits, \
		32, 1)

