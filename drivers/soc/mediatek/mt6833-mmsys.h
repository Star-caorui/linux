#ifndef __SOC_MEDIATEK_MT6833_MMSYS_H
#define __SOC_MEDIATEK_MT6833_MMSYS_H

/*
 * From MediaTek's mtk_drm_ddp.c (the MT6833 tables and
 * mtk_ddp_{mout_en,sel_in,sout_sel,ovl_bg_blend_en}_MT6833()).
 *
 * Unlike MT8192, OVL0_2L feeds OVL0 (not the other way around), the RDMA0
 * input selector and the OVL multiple outputs sit at other offsets, and
 * CCORR0 connects to AAL0 directly.
 */
#define MT6833_MMSYS_OVL_CON			0xf04
#define MT6833_DISP_RDMA0_RSZ0_SOUT_SEL		0xf0c
#define MT6833_DISP_TOVL0_OUT0_MOUT_EN		0xf14
#define MT6833_DISP_TOVL0_OUT1_MOUT_EN		0xf18
#define MT6833_DISP_DITHER0_MOUT_EN		0xf20
#define MT6833_DISP_RDMA0_SEL_IN		0xf28
#define MT6833_DISP_DSI0_SEL_IN			0xf30

#define MT6833_DISP_OVL0_GO_BLEND		BIT(0)
#define MT6833_DISP_OVL0_2L_GO_BG		BIT(3)
#define MT6833_OVL0_2L_MOUT_EN_DISP_RDMA0	BIT(0)
#define MT6833_OVL0_MOUT_EN_DISP_RDMA0		BIT(0)
#define MT6833_DITHER0_MOUT_EN_DSI0		BIT(0)
#define MT6833_RDMA0_SOUT_SEL_MASK		GENMASK(1, 0)
#define MT6833_RDMA0_SOUT_COLOR0		0x1
#define MT6833_RDMA0_SEL_IN_MASK		GENMASK(1, 0)
#define MT6833_RDMA0_SEL_IN_OVL0		0x0
#define MT6833_RDMA0_SEL_IN_OVL0_2L		0x2
#define MT6833_DSI0_SEL_IN_MASK			GENMASK(1, 0)
#define MT6833_DSI0_SEL_IN_DITHER0		0x1

static const struct mtk_mmsys_routes mmsys_mt6833_routing_table[] = {
	MMSYS_ROUTE(OVL_2L, 0, OVL, 0,
		    MT6833_MMSYS_OVL_CON, MT6833_DISP_OVL0_2L_GO_BG,
		    MT6833_DISP_OVL0_2L_GO_BG),
	MMSYS_ROUTE(OVL, 0, RDMA, 0,
		    MT6833_MMSYS_OVL_CON, MT6833_DISP_OVL0_GO_BLEND,
		    MT6833_DISP_OVL0_GO_BLEND),
	MMSYS_ROUTE(OVL, 0, RDMA, 0,
		    MT6833_DISP_TOVL0_OUT1_MOUT_EN, MT6833_OVL0_MOUT_EN_DISP_RDMA0,
		    MT6833_OVL0_MOUT_EN_DISP_RDMA0),
	MMSYS_ROUTE(OVL, 0, RDMA, 0,
		    MT6833_DISP_RDMA0_SEL_IN, MT6833_RDMA0_SEL_IN_MASK,
		    MT6833_RDMA0_SEL_IN_OVL0),
	MMSYS_ROUTE(OVL_2L, 0, RDMA, 0,
		    MT6833_DISP_TOVL0_OUT0_MOUT_EN, MT6833_OVL0_2L_MOUT_EN_DISP_RDMA0,
		    MT6833_OVL0_2L_MOUT_EN_DISP_RDMA0),
	MMSYS_ROUTE(OVL_2L, 0, RDMA, 0,
		    MT6833_DISP_RDMA0_SEL_IN, MT6833_RDMA0_SEL_IN_MASK,
		    MT6833_RDMA0_SEL_IN_OVL0_2L),
	MMSYS_ROUTE(RDMA, 0, COLOR, 0,
		    MT6833_DISP_RDMA0_RSZ0_SOUT_SEL, MT6833_RDMA0_SOUT_SEL_MASK,
		    MT6833_RDMA0_SOUT_COLOR0),
	MMSYS_ROUTE(DITHER, 0, DSI, 0,
		    MT6833_DISP_DITHER0_MOUT_EN, MT6833_DITHER0_MOUT_EN_DSI0,
		    MT6833_DITHER0_MOUT_EN_DSI0),
	MMSYS_ROUTE(DITHER, 0, DSI, 0,
		    MT6833_DISP_DSI0_SEL_IN, MT6833_DSI0_SEL_IN_MASK,
		    MT6833_DSI0_SEL_IN_DITHER0),
};

#endif /* __SOC_MEDIATEK_MT6833_MMSYS_H */
